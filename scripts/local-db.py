#!/usr/bin/env python3
"""Isolated local Supabase lifecycle; never links to a hosted project."""
import argparse
import hashlib
import json
import re
import shutil
import socket
import subprocess
from pathlib import Path
from urllib.error import HTTPError
from urllib.request import Request, urlopen
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[1]
RUNTIME = ROOT / ".supabase-local"
CONFIG = RUNTIME / "supabase" / "config.toml"
MARKER = "# Generated by scripts/local-db.py; local development only."
PASSWORD = "Weblix-local-only-2026!"
EMAILS = ["owner-one@example.test", "owner-two@example.test"]


def prepare():
    CONFIG.parent.mkdir(parents=True, exist_ok=True)
    if not CONFIG.exists():
        # Reserve a free block; Docker still checks for races during startup.
        for base in range(55000, 62000, 10):
            sockets = []
            try:
                for port in range(base, base + 10):
                    sock = socket.socket()
                    sockets.append(sock)
                    sock.bind(("0.0.0.0", port))
            except OSError:
                continue
            finally:
                for sock in sockets:
                    sock.close()
            break
        else:
            raise RuntimeError("No free local port block; stop only an unused owned stack.")
        config = (ROOT / "supabase/config.toml").read_text()
        ident = hashlib.sha256(str(ROOT).encode()).hexdigest()[:12]
        config = config.replace('project_id = "weblix-local"', f'project_id = "weblix-{ident}"')
        config = re.sub(r"5432([0-9])", lambda m: str(base + int(m[1])), config)
        CONFIG.write_text(config)
    else:
        # Refresh template settings while retaining this stack's allocated ports.
        current = CONFIG.read_text()
        base = int(re.search(r"(?m)^port = (\d+)$", current)[1]) - 1
        config = (ROOT / "supabase/config.toml").read_text()
        ident = hashlib.sha256(str(ROOT).encode()).hexdigest()[:12]
        config = config.replace('project_id = "weblix-local"', f'project_id = "weblix-{ident}"')
        config = re.sub(r"5432([0-9])", lambda m: str(base + int(m[1])), config)
        CONFIG.write_text(config)
    # Always replay current tracked migrations, not stale copies from earlier runs.
    target = CONFIG.parent / "migrations"
    if target.exists():
        shutil.rmtree(target)
    shutil.copytree(ROOT / "supabase/migrations", target)


def private_log(output):
    # Keep runner diagnostics (which may contain credentials) out of public output.
    log = RUNTIME / "last-error.log"
    log.touch(mode=0o600, exist_ok=True)
    log.chmod(0o600)
    log.write_text(output)
    return log


def cli(*args, include_stderr=False):
    try:
        result = subprocess.run(
            ["supabase", "--workdir", str(RUNTIME), *args],
            capture_output=True, text=True,
        )
    except FileNotFoundError:
        raise RuntimeError("Supabase CLI is required; install it before running this command.") from None
    if result.returncode:
        # CLI failures may contain connection credentials: retain diagnostics locally.
        log = private_log(result.stdout + result.stderr)
        raise RuntimeError(f"Supabase command failed; inspect {log} locally (do not publish raw logs).")
    return result.stdout + result.stderr if include_stderr else result.stdout


def feature_tests():
    """Refresh tracked suites and require a positive pg_prove summary."""
    discovery = subprocess.run(
        ["git", "-C", str(ROOT), "ls-files", "-z", "--", "supabase/tests"],
        capture_output=True, text=True, check=True,
    )
    suites = sorted(Path(name) for name in discovery.stdout.split("\0")
                    if name and name.endswith(".sql"))
    if not suites:
        raise RuntimeError("No tracked SQL suites found in supabase/tests; no feature tests ran.")
    for suite in suites:
        source = ROOT / suite
        if not source.is_file() or source.is_symlink() or not source.resolve().is_relative_to(ROOT.resolve()):
            raise RuntimeError("Tracked SQL suite is missing or outside this worktree; no feature tests ran.")
    target = CONFIG.parent / "tests"
    if target.exists():
        shutil.rmtree(target)
    for suite in suites:
        destination = RUNTIME / suite
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ROOT / suite, destination)
    output = cli("test", "db", "--local", *(suite.as_posix() for suite in suites),
                 include_stderr=True)
    summary = re.search(r"Files=(\d+),\s*Tests=(\d+)", output)
    if (not summary or int(summary[1]) != len(suites) or int(summary[2]) == 0
            or not re.search(r"(?m)^Result:\s*PASS\s*$", output)
            or "All tests successful." not in output
            or re.search(r"(?im)^\s*(?:not ok\b|Bail out!)", output)):
        log = private_log(output)
        raise RuntimeError(f"Feature tests did not report a complete passing run; inspect {log} locally (do not publish raw logs).")
    print(f"PASS: feature SQL suites: {summary[1]}; assertions: {summary[2]}.")
    for suite in suites:
        print(f"  {suite.as_posix()}")


def status():
    info = json.loads(cli("status", "--output", "json"))
    url = urlparse(info["API_URL"])
    if url.scheme != "http" or url.hostname not in {"127.0.0.1", "localhost", "::1"}:
        raise RuntimeError("Refusing to seed or connect the app to a non-local API.")
    return info


def request(info, path, token=None, data=None, method=None):
    headers = {"apikey": info["ANON_KEY"], "Content-Type": "application/json"}
    if token:
        headers["Authorization"] = "Bearer " + token
    req = Request(info["API_URL"] + path, headers=headers, method=method,
                  data=json.dumps(data).encode() if data is not None else None)
    with urlopen(req, timeout=20) as response:
        body = response.read()
        return json.loads(body) if body else None


def login(info, email):
    return request(info, "/auth/v1/token?grant_type=password",
                   data={"email": email, "password": PASSWORD})["access_token"]


def seed(info):
    for index, email in enumerate(EMAILS, 1):
        try:
            token = login(info, email)
        except HTTPError as error:
            if error.code != 400:
                raise
            request(info, "/auth/v1/signup", data={"email": email, "password": PASSWORD})
            token = login(info, email)
        user = request(info, "/auth/v1/user", token)["id"]
        fixture = f"Local Demo Roofing {index}"
        rows = request(info, "/rest/v1/businesses?select=id&name=eq." + fixture.replace(" ", "%20"), token)
        if not rows:
            request(info, "/rest/v1/businesses", token, {"owner_id": user, "name": fixture})


def environment(info):
    path = ROOT / "apps/web/.env.local"
    if path.exists() and not path.read_text().startswith(MARKER + "\n"):
        raise RuntimeError("Existing apps/web/.env.local was preserved. Use a fresh worktree or move it yourself before configuring local development.")
    path.write_text(MARKER + "\n" + "\n".join([
        "NEXT_PUBLIC_APP_NAME=weblix-platform",
        "NEXT_PUBLIC_APP_URL=http://localhost:3000",
        "NEXT_PUBLIC_SUPABASE_URL=" + info["API_URL"],
        "NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=" + info["ANON_KEY"],
        "TEST_USER_ONE_EMAIL=" + EMAILS[0], "TEST_USER_TWO_EMAIL=" + EMAILS[1],
        "TEST_USER_PASSWORD=" + PASSWORD, "",
    ]))
    path.chmod(0o600)


def check(info):
    one, two = [login(info, email) for email in EMAILS]
    a = request(info, "/rest/v1/businesses?select=id,owner_id,name", one)
    b = request(info, "/rest/v1/businesses?select=id,owner_id,name", two)
    assert a and b, "Both users need fixtures"
    assert not ({r["id"] for r in a} & {r["id"] for r in b}), "Owner isolation failed"
    ident = a[0]["id"]
    assert request(info, "/rest/v1/businesses?select=id&id=eq." + ident, two) == [], "Cross-owner read succeeded"
    before = a[0]["name"]
    request(info, "/rest/v1/businesses?id=eq." + ident, two, {"name": "Unauthorized"}, "PATCH")
    request(info, "/rest/v1/businesses?id=eq." + ident, two, method="DELETE")
    after = request(info, "/rest/v1/businesses?select=name&id=eq." + ident, one)
    assert after == [{"name": before}], "Cross-owner write changed a record"
    print("PASS: business smoke check: both users authenticate; fixtures persist; cross-owner read/update/delete are blocked. Feature SQL suites were not run.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["start", "reset", "up", "stop", "status", "check", "test"])
    command = parser.parse_args().command
    if command != "start" and not CONFIG.exists():
        parser.error("No runtime for this worktree. Run start first.")
    if command in {"start", "reset", "up"}:
        prepare()
    if command == "start":
        cli("start")
    elif command == "reset":
        cli("db", "reset", "--local", "--yes")
    elif command == "up":
        cli("migration", "up", "--local")
    elif command == "stop":
        cli("stop")
        print("Stopped this worktree's Supabase stack; data retained.")
        return
    info = status()
    if command in {"start", "reset"}:
        seed(info)
        environment(info)
    if command == "check":
        check(info)
    elif command == "test":
        feature_tests()
    else:
        print("Local API:", info["API_URL"])
        print("Runtime:", RUNTIME)
        print("No hosted project was linked or modified.")


if __name__ == "__main__":
    main()
